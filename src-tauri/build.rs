fn main() {
    google_oauth_client();
    shipped_skills();
    let commands = app_commands();
    let withheld = withheld_from_agentless_windows(commands);
    write_command_set(
        "all-commands",
        "Every app command: for the windows that run agent turns.",
        commands.iter().copied(),
    );
    write_command_set(
        "agentless-commands",
        "Every app command but the ones withheld from windows that run no agent turn.",
        commands
            .iter()
            .copied()
            .filter(|c| !withheld.iter().any(|w| w == c)),
    );
    let manifest = tauri_build::AppManifest::new().commands(commands);
    let mut attributes = tauri_build::Attributes::new().app_manifest(manifest);
    if embed_windows_manifest() {
        attributes = attributes
            .windows_attributes(tauri_build::WindowsAttributes::new_without_app_manifest());
    }
    if let Err(e) = tauri_build::try_build(attributes) {
        panic!("tauri build failed: {e:#}");
    }
}

/// On Windows, `windows/app.manifest` (Common Controls v6) in every target
/// the linker makes, the test binaries too. Returns whether it did.
///
/// tauri-build links its own copy of that manifest into the app's binary
/// only. The unit-test binary links the same code, which now imports
/// `TaskDialogIndirect`, a function only Common Controls v6 has; without the
/// manifest Windows loads v5, and the binary dies before its first test
/// (`STATUS_ENTRYPOINT_NOT_FOUND`). So tauri-build is told to leave the
/// manifest out, and the linker embeds it everywhere instead.
fn embed_windows_manifest() -> bool {
    let os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let env = std::env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();
    if os != "windows" || env != "msvc" {
        return false;
    }
    println!("cargo:rerun-if-changed=windows/app.manifest");
    let dir = std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    let path = std::path::Path::new(&dir)
        .join("windows")
        .join("app.manifest");
    assert!(path.is_file(), "{} is missing", path.display());
    println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
    println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", path.display());
    true
}

/// Every command `src/lib.rs` hands `generate_handler!`, by its own name.
///
/// Naming them gives each an `allow-*` permission, and from then on a window
/// may call only what its capability grants (see `capabilities/`). Read from
/// the handler list itself, so a new command can't be left out of the sets
/// [`write_command_set`] writes.
fn app_commands() -> &'static [&'static str] {
    println!("cargo:rerun-if-changed=src/lib.rs");
    let src = std::fs::read_to_string("src/lib.rs").expect("read src/lib.rs");
    let start = src
        .find("generate_handler![")
        .expect("src/lib.rs has no generate_handler!");
    let body = &src[start + "generate_handler![".len()..];
    let body = &body[..body.find(']').expect("generate_handler! is not closed")];
    let names: Vec<&'static str> = body
        .split(',')
        .map(str::trim)
        .filter(|path| !path.is_empty())
        .map(|path| {
            let name = path.rsplit("::").next().unwrap_or(path);
            assert!(
                name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'),
                "generate_handler! entry {path:?} is not a plain command path"
            );
            &*Box::leak(name.to_string().into_boxed_str())
        })
        .collect();
    Box::leak(names.into_boxed_slice())
}

/// The commands `acl/withheld-from-agentless-windows.txt` names, each checked
/// against `commands` so a rename can't leave one granted.
///
/// Withheld rather than denied: Tauri applies a `deny-*` to every window,
/// whichever capability names it, so the only way to keep a command from some
/// windows is to leave it out of what they are granted.
fn withheld_from_agentless_windows(commands: &[&str]) -> Vec<String> {
    let path = "acl/withheld-from-agentless-windows.txt";
    println!("cargo:rerun-if-changed={path}");
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("read {path}: {e}"));
    let withheld: Vec<String> = text
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(str::to_string)
        .collect();
    for name in &withheld {
        assert!(
            commands.contains(&name.as_str()),
            "{path} names {name}, which is not in generate_handler!"
        );
    }
    withheld
}

/// `permissions/<id>.toml`: a set granting `commands`. Generated beside
/// tauri-build's own `permissions/autogenerated/`, and like it not committed.
fn write_command_set<'a>(id: &str, description: &str, commands: impl Iterator<Item = &'a str>) {
    let allows: Vec<String> = commands
        .map(|c| format!("  \"allow-{}\",", c.replace('_', "-")))
        .collect();
    let toml = format!(
        "# Automatically generated by build.rs - DO NOT EDIT!\n\n\
         [[set]]\n\
         identifier = \"{id}\"\n\
         description = \"{description}\"\n\
         permissions = [\n{}\n]\n",
        allows.join("\n")
    );
    let path = std::path::PathBuf::from(format!("permissions/{id}.toml"));
    std::fs::create_dir_all("permissions").expect("create permissions/");
    // Only when it changed, so cargo doesn't see a new file on every build.
    if std::fs::read_to_string(&path).ok().as_deref() != Some(toml.as_str()) {
        std::fs::write(&path, toml).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
    }
}

/// Compile in the skills under `resources/skills/`, which `skills::shipped`
/// copies into the user's skills folder. Embedded rather than bundled as
/// resources, so dev and every installer find them the same way.
///
/// Writes `$OUT_DIR/shipped_skills.rs`: `SHIPPED`, each file's path relative
/// to `resources/skills/` and its bytes, sorted by path.
fn shipped_skills() {
    use std::path::{Path, PathBuf};
    let root = Path::new("resources/skills");
    println!("cargo:rerun-if-changed={}", root.display());
    fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                walk(&path, out);
            } else {
                out.push(path);
            }
        }
    }
    let mut files = Vec::new();
    walk(root, &mut files);
    files.sort();
    let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let mut code = String::from("pub const SHIPPED: &[(&str, &[u8])] = &[\n");
    for file in &files {
        let rel = file
            .strip_prefix(root)
            .unwrap()
            .to_string_lossy()
            .replace('\\', "/");
        let abs = Path::new(&manifest).join(file);
        code.push_str(&format!(
            "    ({rel:?}, include_bytes!({:?})),\n",
            abs.to_string_lossy()
        ));
    }
    code.push_str("];\n");
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("shipped_skills.rs");
    std::fs::write(out, code).unwrap();
}

/// Compile in Haruspex's Google OAuth desktop client, when this checkout has
/// one (`google-oauth.json`, gitignored — see `docs/google-sign-in.md`).
///
/// Without it the build still works; "Sign in with Google" is just not
/// offered. The file is watched only once it exists: a `rerun-if-changed` on a
/// missing path reruns this script on every build, so after adding the file
/// for the first time, touch this one.
fn google_oauth_client() {
    let path = "google-oauth.json";
    let Ok(text) = std::fs::read_to_string(path) else {
        return;
    };
    println!("cargo:rerun-if-changed={path}");
    let json: serde_json::Value =
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("{path} is not valid JSON: {e}"));
    for (field, var) in [
        ("clientId", "HARUSPEX_GOOGLE_CLIENT_ID"),
        ("clientSecret", "HARUSPEX_GOOGLE_CLIENT_SECRET"),
    ] {
        let value = json
            .get(field)
            .and_then(|v| v.as_str())
            .unwrap_or_else(|| panic!("{path} has no \"{field}\""));
        println!("cargo:rustc-env={var}={value}");
    }
}
