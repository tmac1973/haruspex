/// How often orphaned sessions are swept. Cheap: a map walk over at most
/// [`super::relay::MAX_SESSIONS`] entries.
const REAP_INTERVAL: Duration = Duration::from_secs(15);

/// Longest prompt a remote client may send. Generous for a chat box, small
/// enough that a paste bomb is not a memory event.
const MAX_MESSAGE_BYTES: usize = 32 * 1024;

/// Longest answer read aloud in one request — around four minutes of speech.
const MAX_SPEECH_CHARS: usize = 4000;

/// The TTS sidecar's port, and the app's default voice. Kept local rather than
/// threaded through the config so that changing the host's voice in Settings
/// cannot restart the server and drop a guest mid-answer.
const TTS_PORT: u16 = 3001;
const DEFAULT_VOICE: &str = "af_heart";

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RemoteConfig {
    pub port: u16,
    /// Generated by the frontend (Web Crypto) and stored in settings. Rust
    /// never mints it, so rotation is a settings change and not an IPC dance.
    pub token: String,
    /// Bind `0.0.0.0` rather than loopback. False is useful for testing the
    /// server without exposing anything to the network.
    pub bind_all: bool,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RemoteStatus {
    pub running: bool,
    pub port: Option<u16>,
    pub bind_all: bool,
    pub sessions: usize,
}

/// Everything the HTTP layer needs from the app it is embedded in.
///
/// Behind a trait because the HTTP surface is worth testing end to end — token
/// handling especially — and standing up an `AppHandle` to do it is not
/// realistic.
pub trait Host: Send + Sync + 'static {
    /// Hand a prompt to whoever runs turns — in the app, a Tauri event to the
    /// webview, which is the only thing that can run one. An error means nobody
    /// is listening, and the caller fails the turn rather than leaving the
    /// client waiting on an answer that will never come.
    fn dispatch(&self, request: PromptRequest) -> Result<(), String>;

    fn cancel(&self, turn_id: &str);

    /// Make sure the speech sidecar is running, starting it if not.
    ///
    /// The app starts koko lazily — the host's own Listen button starts it on
    /// first use — so a guest tapping Listen on a machine whose owner has not
    /// used speech this session finds nothing listening on the port.
    fn ensure_speech(&self) -> BoxFuture<Result<(), String>>;

    /// Deliver a guest's answer to the turn that is parked on the question.
    fn answer(&self, turn_id: &str, answer: &Answer);
}

/// A boxed future, because [`Host`] is a trait object and this crate has no
/// async-trait dependency.
pub type BoxFuture<T> = Pin<Box<dyn Future<Output = T> + Send>>;

#[derive(Clone)]
struct AppState {
    host: Arc<dyn Host>,
    relay: Arc<Relay>,
    token: Arc<String>,
}

pub struct Running {
    pub port: u16,
    pub bind_all: bool,
    pub token: String,
    shutdown: watch::Sender<bool>,
}

impl Running {
    pub fn stop(&self) {
        let _ = self.shutdown.send(true);
    }
}

/// Bind and serve. Returns once the socket is listening, so a caller that gets
/// `Ok` can hand out the link immediately.
pub async fn start(
    host: Arc<dyn Host>,
    relay: Arc<Relay>,
    config: RemoteConfig,
) -> Result<Running, String> {
    if config.token.trim().is_empty() {
        return Err("refusing to start without an access token".into());
    }

    let bind_ip = if config.bind_all {
        IpAddr::V4(Ipv4Addr::UNSPECIFIED)
    } else {
        IpAddr::V4(Ipv4Addr::LOCALHOST)
    };
    let addr = SocketAddr::new(bind_ip, config.port);

    let listener = tokio::net::TcpListener::bind(addr).await.map_err(|e| {
        format!("could not listen on {addr}: {e} — another program may already have that port")
    })?;
    let port = listener
        .local_addr()
        .map(|a| a.port())
        .unwrap_or(config.port);

    let state = AppState {
        host: host.clone(),
        relay: relay.clone(),
        token: Arc::new(config.token.clone()),
    };

    let router = Router::new()
        .route("/", get(index))
        .route("/app.css", get(stylesheet))
        .route("/app.js", get(script))
        .route("/api/health", get(health))
        .route("/api/chat", post(chat))
        .route("/api/cancel", post(cancel))
        .route("/api/answer", post(answer))
        .route("/api/speak", post(speak))
        .route("/api/stream/{session}", get(stream))
        .with_state(state);

    let (shutdown, mut shutdown_rx) = watch::channel(false);

    let mut serve_rx = shutdown.subscribe();
    tokio::spawn(async move {
        let served = axum::serve(listener, router).with_graceful_shutdown(async move {
            let _ = serve_rx.wait_for(|stop| *stop).await;
        });
        if let Err(e) = served.await {
            log::error!("[remote] server stopped: {e}");
        }
    });

    // Orphan sweep: a client that closed its tab mid-answer must not hold an
    // inference slot until the app restarts.
    let reap_host = host.clone();
    let reap_relay = relay.clone();
    tokio::spawn(async move {
        loop {
            tokio::select! {
                _ = tokio::time::sleep(REAP_INTERVAL) => {}
                _ = shutdown_rx.wait_for(|stop| *stop) => break,
            }
            for turn_id in reap_relay.reap() {
                log::info!("[remote] abandoning turn {turn_id}: nobody is listening");
                reap_host.cancel(&turn_id);
            }
        }
    });

    log::info!(
        "[remote] serving on {}:{port}",
        if config.bind_all {
            "0.0.0.0"
        } else {
            "127.0.0.1"
        }
    );

    Ok(Running {
        port,
        bind_all: config.bind_all,
        token: config.token,
        shutdown,
    })
}

