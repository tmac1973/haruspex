/// `None` when the caller is authorised; otherwise the response to send back
/// instead of handling the request.
fn unauthorised(state: &AppState, headers: &HeaderMap, uri: &Uri) -> Option<Response> {
    let provided = auth::extract_token(headers, uri.query()).unwrap_or_default();
    if auth::token_matches(&state.token, &provided) {
        None
    } else {
        Some((StatusCode::UNAUTHORIZED, "not for you").into_response())
    }
}

/// Unauthenticated on purpose: the host's own settings page uses this to say
/// whether the server is actually up, and it reveals nothing but that.
async fn health() -> impl IntoResponse {
    Json(serde_json::json!({ "ok": true, "service": "haruspex" }))
}

async fn index(State(state): State<AppState>, headers: HeaderMap, uri: Uri) -> Response {
    if unauthorised(&state, &headers, &uri).is_some() {
        // Deliberately says nothing about what is running here.
        return no_cache(Html(NO_TOKEN_PAGE).into_response());
    }
    let page = CLIENT_HTML.replace("{{host}}", &html_escape(&host_name()));
    let mut response = no_cache(Html(page).into_response());
    // So a guest who bookmarks the page, or adds it to their home screen
    // without the query string, is not locked out of their own link.
    if let Ok(cookie) = auth::token_cookie(&state.token).parse() {
        response.headers_mut().insert(SET_COOKIE, cookie);
    }
    response
}

/// The client's assets are unauthenticated on purpose: they are a static page
/// and a static script, identical for everyone, and gating them would only mean
/// a guest whose cookie lapsed sees an unstyled page instead of a clear error
/// from the API.
async fn stylesheet() -> Response {
    asset(CLIENT_CSS, "text/css; charset=utf-8")
}

async fn script() -> Response {
    asset(CLIENT_JS, "text/javascript; charset=utf-8")
}

fn asset(body: &'static str, content_type: &'static str) -> Response {
    let mut response = body.into_response();
    response
        .headers_mut()
        .insert(CONTENT_TYPE, content_type.parse().expect("static mime"));
    no_cache(response)
}

/// Never stored, not merely revalidated.
///
/// An app update changes these files, and a guest holding an older script that
/// talks to a newer API is a bug nobody will diagnose from the other end of a
/// phone call. `no-cache` asks the browser to revalidate, but these responses
/// carry no validator, and a phone's back-forward cache will happily keep a
/// whole page anyway — so the instruction is not to keep it at all.
fn no_cache(mut response: Response) -> Response {
    response.headers_mut().insert(
        CACHE_CONTROL,
        "no-store, must-revalidate".parse().expect("static header"),
    );
    response
}

/// Whose computer this is, for the notice on the page. Best effort by design —
/// the fallback still says something true.
fn host_name() -> String {
    std::env::var("COMPUTERNAME")
        .ok()
        .or_else(|| std::env::var("HOSTNAME").ok())
        .or_else(|| std::fs::read_to_string("/etc/hostname").ok())
        .map(|name| name.trim().to_string())
        .filter(|name| !name.is_empty())
        .unwrap_or_else(|| "this computer".to_string())
}

/// The hostname comes from the OS rather than from a request, but it is still
/// interpolated into a page, and "trusted enough" is how injection happens.
fn html_escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct ChatRequest {
    session_id: String,
    message: String,
    /// What the guest calls themselves. Optional: a guest who skips the
    /// question still gets a conversation, just a generically named one.
    #[serde(default)]
    client_label: Option<String>,
}

async fn chat(
    State(state): State<AppState>,
    headers: HeaderMap,
    uri: Uri,
    Json(body): Json<ChatRequest>,
) -> Response {
    if let Some(response) = unauthorised(&state, &headers, &uri) {
        return response;
    }
    let message = body.message.trim().to_string();
    if message.is_empty() {
        return (StatusCode::BAD_REQUEST, "empty message").into_response();
    }
    if message.len() > MAX_MESSAGE_BYTES {
        return (StatusCode::PAYLOAD_TOO_LARGE, "message too long").into_response();
    }

    match state
        .relay
        .begin_turn(&body.session_id, message, body.client_label)
    {
        Ok(request) => {
            let turn_id = request.turn_id.clone();
            // The frontend is the only thing that can run a turn; if the
            // handoff fails there is nobody to answer, so the turn is failed
            // rather than left waiting forever.
            if let Err(e) = state.host.dispatch(request) {
                let _ = state
                    .relay
                    .fail(&turn_id, "the desktop app is not listening".into());
                log::error!("[remote] could not hand off prompt: {e}");
                return (
                    StatusCode::SERVICE_UNAVAILABLE,
                    "the desktop app is not ready",
                )
                    .into_response();
            }
            (
                StatusCode::ACCEPTED,
                Json(serde_json::json!({ "turnId": turn_id })),
            )
                .into_response()
        }
        Err(e) => relay_error_response(e),
    }
}

fn relay_error_response(error: RelayError) -> Response {
    let status = match error {
        RelayError::Busy => StatusCode::CONFLICT,
        RelayError::TooManySessions => StatusCode::SERVICE_UNAVAILABLE,
        RelayError::RateLimited => StatusCode::TOO_MANY_REQUESTS,
        RelayError::BadSessionId => StatusCode::BAD_REQUEST,
        RelayError::UnknownTurn => StatusCode::NOT_FOUND,
    };
    (status, error.message()).into_response()
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct CancelRequest {
    session_id: String,
}

async fn cancel(
    State(state): State<AppState>,
    headers: HeaderMap,
    uri: Uri,
    Json(body): Json<CancelRequest>,
) -> Response {
    if let Some(response) = unauthorised(&state, &headers, &uri) {
        return response;
    }
    match state.relay.in_flight_turn(&body.session_id) {
        Some(turn_id) => {
            state.host.cancel(&turn_id);
            StatusCode::ACCEPTED.into_response()
        }
        // Nothing to stop is a success: the client wanted no turn running, and
        // there is no turn running.
        None => StatusCode::NO_CONTENT.into_response(),
    }
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct AnswerRequest {
    session_id: String,
    #[serde(flatten)]
    answer: Answer,
}

/// The guest's reply to a question the model asked.
///
/// The turn is parked on it holding an inference slot, so this is the fastest
/// path in the file: validate, hand it to the driver, return.
async fn answer(
    State(state): State<AppState>,
    headers: HeaderMap,
    uri: Uri,
    Json(body): Json<AnswerRequest>,
) -> Response {
    if let Some(response) = unauthorised(&state, &headers, &uri) {
        return response;
    }
    match state.relay.answer(&body.session_id, &body.answer) {
        Ok(turn_id) => {
            state.host.answer(&turn_id, &body.answer);
            StatusCode::ACCEPTED.into_response()
        }
        // The question has already been answered or the turn moved on. Not an
        // error worth alarming a guest about — a double tap looks exactly like
        // this — but not something to deliver either.
        Err(_) => StatusCode::NO_CONTENT.into_response(),
    }
}

#[derive(Debug, Deserialize)]
struct SpeakRequest {
    text: String,
}

/// Reads an answer aloud, by relaying to the TTS sidecar the app already runs.
///
/// No synthesis happens here and no Tauri state is touched: koko listens on
/// loopback and speaks an OpenAI-compatible dialect, so this is a proxy with a
/// container swap. If the host has never turned TTS on, the sidecar is not
/// running and the guest gets a plain "not available" rather than a hang.
async fn speak(
    State(state): State<AppState>,
    headers: HeaderMap,
    uri: Uri,
    Json(body): Json<SpeakRequest>,
) -> Response {
    if let Some(response) = unauthorised(&state, &headers, &uri) {
        return response;
    }
    let text = body.text.trim();
    if text.is_empty() {
        return (StatusCode::BAD_REQUEST, "nothing to say").into_response();
    }
    // Long answers are truncated rather than refused: hearing the first part is
    // more useful than an error, and synthesising ten minutes of audio to serve
    // one tap is not.
    let text = crate::text_util::truncate_at_char_boundary(text, MAX_SPEECH_CHARS);

    // Start the sidecar if this is the first speech on this machine since
    // launch — which it usually is, since the host has their own ears and does
    // not need their own answers read aloud.
    if let Err(e) = state.host.ensure_speech().await {
        log::warn!("[remote] speech could not be started: {e}");
        return (
            StatusCode::SERVICE_UNAVAILABLE,
            "the host's speech engine could not start",
        )
            .into_response();
    }

    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(120))
        .build();
    let Ok(client) = client else {
        return (
            StatusCode::INTERNAL_SERVER_ERROR,
            "could not build a client",
        )
            .into_response();
    };

    let response = client
        .post(format!("http://127.0.0.1:{TTS_PORT}/v1/audio/speech"))
        .json(&serde_json::json!({
            "model": "tts-1",
            "input": text,
            "voice": DEFAULT_VOICE,
            "response_format": "pcm"
        }))
        .send()
        .await;

    let audio = match response {
        Ok(response) if response.status().is_success() => response.bytes().await,
        Ok(response) => {
            log::warn!("[remote] speech failed: {}", response.status());
            return (StatusCode::BAD_GATEWAY, "speech is not available").into_response();
        }
        Err(e) => {
            // Started, and still unreachable: not something a guest can act on.
            log::warn!("[remote] speech unreachable: {e}");
            return (StatusCode::SERVICE_UNAVAILABLE, "speech is not available").into_response();
        }
    };
    let Ok(audio) = audio else {
        return (StatusCode::BAD_GATEWAY, "speech was cut off").into_response();
    };
    if audio.len() < 100 {
        return (StatusCode::BAD_GATEWAY, "speech produced no audio").into_response();
    }

    let mut response = wav_from_pcm(&audio).into_response();
    response
        .headers_mut()
        .insert(CONTENT_TYPE, "audio/wav".parse().expect("static mime"));
    no_cache(response)
}

/// Wrap koko's raw PCM in the 44-byte header a browser needs to play it.
///
/// The sidecar returns signed 16-bit mono at 24kHz — the same assumption the
/// desktop playback path makes — and `<audio>` will not touch headerless PCM.
fn wav_from_pcm(pcm: &[u8]) -> Vec<u8> {
    const CHANNELS: u16 = 1;
    const SAMPLE_RATE: u32 = 24_000;
    const BITS: u16 = 16;
    let byte_rate = SAMPLE_RATE * CHANNELS as u32 * (BITS / 8) as u32;
    let block_align = CHANNELS * (BITS / 8);
    let data_len = pcm.len() as u32;

    let mut out = Vec::with_capacity(44 + pcm.len());
    out.extend_from_slice(b"RIFF");
    out.extend_from_slice(&(36 + data_len).to_le_bytes());
    out.extend_from_slice(b"WAVEfmt ");
    out.extend_from_slice(&16u32.to_le_bytes()); // PCM header size
    out.extend_from_slice(&1u16.to_le_bytes()); // uncompressed
    out.extend_from_slice(&CHANNELS.to_le_bytes());
    out.extend_from_slice(&SAMPLE_RATE.to_le_bytes());
    out.extend_from_slice(&byte_rate.to_le_bytes());
    out.extend_from_slice(&block_align.to_le_bytes());
    out.extend_from_slice(&BITS.to_le_bytes());
    out.extend_from_slice(b"data");
    out.extend_from_slice(&data_len.to_le_bytes());
    out.extend_from_slice(pcm);
    out
}

async fn stream(
    State(state): State<AppState>,
    Path(session_id): Path<String>,
    headers: HeaderMap,
    uri: Uri,
) -> Response {
    if let Some(response) = unauthorised(&state, &headers, &uri) {
        return response;
    }
    let (rx, snapshot) = match state.relay.subscribe(&session_id) {
        Ok(pair) => pair,
        Err(e) => return relay_error_response(e),
    };

    let guard = SubscriberGuard {
        relay: state.relay.clone(),
        session_id: session_id.clone(),
    };
    let stream = event_stream(rx, snapshot, guard);

    Sse::new(stream)
        .keep_alive(KeepAlive::new().interval(Duration::from_secs(15)))
        .into_response()
}

/// Drops the session's subscriber count when the SSE stream ends, however it
/// ends. Without this a closed tab would look like a listener forever and its
/// turn would never be reaped.
struct SubscriberGuard {
    relay: Arc<Relay>,
    session_id: String,
}

impl Drop for SubscriberGuard {
    fn drop(&mut self) {
        self.relay.unsubscribe(&self.session_id);
    }
}

struct StreamState {
    rx: broadcast::Receiver<RemoteEvent>,
    guard: SubscriberGuard,
    /// The snapshot to send before anything else, so a reconnecting client is
    /// in sync from its first frame.
    pending: Option<RemoteEvent>,
}

fn event_stream(
    rx: broadcast::Receiver<RemoteEvent>,
    snapshot: RemoteEvent,
    guard: SubscriberGuard,
) -> impl Stream<Item = Result<Event, Infallible>> {
    let state = StreamState {
        rx,
        guard,
        pending: Some(snapshot),
    };
    futures_util::stream::unfold(state, |mut state| async move {
        loop {
            if let Some(event) = state.pending.take() {
                return Some((Ok(sse_event(&event)), state));
            }
            match state.rx.recv().await {
                Ok(event) => return Some((Ok(sse_event(&event)), state)),
                // A slow reader missed deltas. Deltas are suffixes, so the gap
                // cannot be papered over — resend the whole buffer instead.
                Err(broadcast::error::RecvError::Lagged(_)) => {
                    state.pending = state.guard.relay.snapshot(&state.guard.session_id);
                    // No snapshot means the session is gone; the stream ends
                    // rather than spinning on a receiver nobody will feed.
                    state.pending.as_ref()?;
                }
                Err(broadcast::error::RecvError::Closed) => return None,
            }
        }
    })
}

fn sse_event(event: &RemoteEvent) -> Event {
    match Event::default().json_data(event) {
        Ok(e) => e,
        // Serialising our own enum cannot realistically fail, but a stream that
        // dies on it would be a mystery; a visible error frame is not.
        Err(e) => Event::default().data(format!(r#"{{"type":"error","message":"{e}"}}"#)),
    }
}

