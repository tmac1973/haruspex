    #[tokio::test]
    async fn a_prompt_reaches_the_sink_and_streams_back() {
        let sink = Arc::new(RecordingSink::default());
        let (base, relay, running) = serve(sink.clone()).await;
        let client = reqwest::Client::new();

        let mut stream = client
            .get(format!("{base}/api/stream/s1?t={TOKEN}"))
            .send()
            .await
            .unwrap();
        assert_eq!(stream.status(), 200);
        // First frame is always a snapshot, so a client is in sync before it
        // has seen a single delta.
        let first = String::from_utf8_lossy(&stream.chunk().await.unwrap().unwrap()).to_string();
        assert!(first.contains("\"type\":\"snapshot\""), "got {first}");

        let accepted = client
            .post(format!("{base}/api/chat?t={TOKEN}"))
            .json(&serde_json::json!({ "sessionId": "s1", "message": "what is a haruspex?" }))
            .send()
            .await
            .unwrap();
        assert_eq!(accepted.status(), 202);

        let dispatched = sink.dispatched.lock().unwrap().clone();
        assert_eq!(dispatched.len(), 1);
        assert_eq!(dispatched[0].message, "what is a haruspex?");
        assert_eq!(dispatched[0].session_id, "s1");

        // Now play the part of the frontend driver.
        relay
            .push_step(
                &dispatched[0].turn_id,
                super::super::relay::Step {
                    id: "c1".into(),
                    label: "Searching the web".into(),
                    status: super::super::relay::StepStatus::Running,
                },
            )
            .unwrap();
        relay
            .push_text(&dispatched[0].turn_id, "a reader of")
            .unwrap();
        relay
            .finish(&dispatched[0].turn_id, "a reader of entrails".into())
            .unwrap();

        let mut seen = String::new();
        while !seen.contains("\"type\":\"done\"") {
            match stream.chunk().await.unwrap() {
                Some(bytes) => seen.push_str(&String::from_utf8_lossy(&bytes)),
                None => panic!("stream ended before the answer: {seen}"),
            }
        }
        // The wire format the client switches on, proven end to end rather
        // than only in the relay's own tests.
        assert!(
            seen.contains("\"type\":\"step\""),
            "no step event in {seen}"
        );
        assert!(
            seen.contains("Searching the web"),
            "no step label in {seen}"
        );
        assert!(seen.contains("a reader of"), "no delta in {seen}");
        assert!(seen.contains("entrails"), "no final text in {seen}");
        running.stop();
    }

